
create table if not exists public.armor_votes (
  id bigint generated by default as identity primary key,
  armor_set_id text not null,
  voter_hash text not null,
  rating integer not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint armor_votes_set_voter_unique
    unique (armor_set_id, voter_hash)
);

create index if not exists armor_votes_set_id_idx
  on public.armor_votes (armor_set_id);

create or replace function public.get_armor_vote_summary()
returns table (
  armor_set_id text,
  vote_count bigint,
  average_rating numeric
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    v.armor_set_id,
    count(*)::bigint as vote_count,
    round(avg(v.rating)::numeric, 2) as average_rating
  from public.armor_votes as v
  group by v.armor_set_id;
$$;

grant usage on schema public to service_role;
grant select, insert, update on public.armor_votes to service_role;
grant usage, select on sequence public.armor_votes_id_seq to service_role;
grant execute on function public.get_armor_vote_summary() to service_role;
